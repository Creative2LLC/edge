#!/usr/bin/env node

/* eslint-disable no-console -- CLI progress output. */

/**
 * Resource taxonomy generator. The backend enums are the single source of the
 * resource tags (values, per-library labels, which library offers each); this
 * script copies them into the two places the frontend needs them:
 *
 *   1. scripts/resource-taxonomy-data.js — the label/section data the resource
 *      blocks read through scripts/resource-taxonomy.js.
 *   2. The static `options` of the taxonomy fields in the resource UE models
 *      (UE selects cannot load options at runtime).
 *
 * Option lists only change which choices authors see; no field is added,
 * removed or reordered, so published cell indexes are untouched. The husky
 * pre-commit hook rebuilds component-models.json from the partials.
 *
 * Usage:
 *   node scripts/build-resource-taxonomy.mjs                          # production API
 *   node scripts/build-resource-taxonomy.mjs --base http://localhost:8000
 *   node scripts/build-resource-taxonomy.mjs --file taxonomy.json     # saved API response
 *   node scripts/build-resource-taxonomy.mjs --dry-run
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Same default as build-s3-options.mjs: authored pages call production.
const DEFAULT_API_BASE_URL = 'https://stunning-dust-ntqeawud3dqy.on-vapor.com';
const DATA_FILE = path.join(repoRoot, 'scripts', 'resource-taxonomy-data.js');
const MODEL_FILES = [
  path.join(repoRoot, 'blocks', 'resource-hero', '_resource-hero.json'),
  path.join(repoRoot, 'blocks', 'resource-details', '_resource-details.json'),
  path.join(repoRoot, 'blocks', 'resource-tags', '_resource-tags.json'),
];
// UE field name -> backend taxonomy field.
const MODEL_FIELDS = {
  audience: 'audience',
  issue: 'issue',
  resourceType: 'resource_type',
  programs: 'programs',
  language: 'language',
};

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const argValue = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : undefined;
};

async function loadTaxonomy() {
  const file = argValue('--file');
  if (file) {
    const payload = JSON.parse(await fs.readFile(path.resolve(file), 'utf8'));
    return payload.data || payload;
  }

  const baseUrl = (argValue('--base') || process.env.RESOURCE_API_BASE_URL || DEFAULT_API_BASE_URL).replace(/\/+$/, '');
  const url = `${baseUrl}/api/resources/taxonomy`;
  console.log(`Reading ${url}`);
  const response = await fetch(url);
  if (response.status === 404) {
    throw new Error(`${url} returned 404 — that backend predates the taxonomy endpoint. Deploy it, or pass --base for one that has it.`);
  }
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}.`);
  return (await response.json()).data;
}

/**
 * Every value either library offers, Prevention's order first. A value whose
 * libraries word it differently shows both, so an author picking "Families"
 * knows the Prevention page will say "Parents/Guardians".
 */
function toModelOptions(taxonomy, field) {
  const entries = new Map(taxonomy.fields[field].map((entry) => [entry.value, entry]));
  const ordered = [...new Set(Object.values(taxonomy.sections)
    .flatMap((section) => section.order[field] || []))];

  return ordered.map((value) => {
    const entry = entries.get(value);
    const { prevention, general } = entry.labels;
    const offered = entry.sections;
    let name = entry.label;
    if (offered.length === 2 && prevention !== general) name = `${general} (Prevention: ${prevention})`;
    else if (offered.length === 1) name = entry.labels[offered[0]];
    return { name, value };
  });
}

/** Serialise to JS in the repo's lint style (single quotes, bare keys, trailing commas). */
function toJs(value, depth = 0) {
  const pad = '  '.repeat(depth + 1);
  const close = '  '.repeat(depth);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value.map((item) => `${pad}${toJs(item, depth + 1)},`).join('\n')}\n${close}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value);
    if (!entries.length) return '{}';
    const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);
    return `{\n${entries.map(([name, item]) => `${pad}${key(name)}: ${toJs(item, depth + 1)},`).join('\n')}\n${close}}`;
  }
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  return JSON.stringify(value);
}

function dataModule(taxonomy) {
  return `// GENERATED by scripts/build-resource-taxonomy.mjs from the backend's
// /api/resources/taxonomy. Do not edit by hand: change the backend enums and
// rerun \`npm run build:taxonomy\`. Read it through scripts/resource-taxonomy.js.
export default ${toJs(taxonomy)};
`;
}

async function main() {
  const taxonomy = await loadTaxonomy();
  if (!taxonomy?.fields || !taxonomy?.sections) throw new Error('The response has no taxonomy data.');

  const changes = [];
  const models = await Promise.all(MODEL_FILES.map(async (file) => {
    const model = JSON.parse(await fs.readFile(file, 'utf8'));
    model.models.forEach((entry) => {
      (entry.fields || []).forEach((field) => {
        const source = MODEL_FIELDS[field.name];
        if (!source || !Array.isArray(field.options)) return;
        field.options = toModelOptions(taxonomy, source);
        changes.push(`${path.basename(file)} ${field.name}: ${field.options.length} options`);
      });
    });
    return { file, model };
  }));

  changes.forEach((line) => console.log(`  ${line}`));
  if (dryRun) {
    console.log('Dry run: no files written.');
    return;
  }

  await fs.writeFile(DATA_FILE, dataModule(taxonomy), 'utf8');
  await Promise.all(models.map(({ file, model }) => fs.writeFile(file, `${JSON.stringify(model, null, 2)}\n`, 'utf8')));
  console.log(`Wrote ${path.relative(repoRoot, DATA_FILE)} and ${models.length} model partials.`);
  console.log('Commit them — the pre-commit hook rebuilds component-models.json.');
}

main().catch((error) => {
  console.error(`build-resource-taxonomy: ${error.message}`);
  process.exitCode = 1;
});
